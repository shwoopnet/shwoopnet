#!/usr/bin/env python3
"""Render the master family table (families.csv) as FAMILY_TABLE.md and print the state counts.

families.csv is the source of truth: one row per family, state, events a year, and the
columns from the Nov 10 listing and from the Forensics desk's cost table. Usage:
python3 build_table.py   (run in this folder; writes ../FAMILY_TABLE.md)
"""
import collections, csv, os

HERE = os.path.dirname(os.path.abspath(__file__))

def state(s):
    s = s.strip()
    return "NEVER READ" if s.startswith("NEVER READ") else ("SWEEP ONLY" if s.startswith("SWEEP ONLY") else "TOUCHED")

def main():
    rows = list(csv.DictReader(open(os.path.join(HERE, "families.csv"))))
    c = collections.Counter(state(r["state"]) for r in rows)
    out = ["# Family census: the master table (Idea Desk B with the Forensics desk)", "",
           "Generated by `census/build_table.py` from `census/families.csv`. Sources, limits and method: `FAMILY_CENSUS_NOV12.md`. "
           "The Nov 10 columns are one Tuesday (UTC) and are LOWER BOUNDS (23 of 24 hours hit the page cap). "
           "Spread, round trip and data kind are the Forensics desk's (`forensics/FAMILY_COSTS_NOV12.md` on `claude/forensics-desk`); blank means no recorder holds that family.", "",
           f"**Counts: families {len(rows)}; TOUCHED {c['TOUCHED']} (a registered test of a mechanism exists); SWEEP ONLY {c['SWEEP ONLY']} "
           f"(only the cheap-tail sweep read it); NEVER READ {c['NEVER READ']}.**", ""]
    head = ["Family", "State", "Events a year", "Events Nov 10", "Contracts a market Nov 10", "Settles after close (minutes)",
            "Spread", "Round trip", "Fee class", "Data kind", "Flag", "Tests and verdicts"]
    keys = ["family", "state", "events_a_year", "events_nov10", "contracts_a_market_nov10", "settle_minutes_nov10",
            "spread", "round_trip", "fee_class", "data_kind", "cost_flag", "tests"]
    for g in ("Sports", "Not sports"):
        out += [f"## {g}", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
        for r in rows:
            if r["group"] == g:
                out.append("| " + " | ".join((r[k] or "").replace("|", "/") for k in keys) + " |")
        out.append("")
    open(os.path.join(HERE, "..", "FAMILY_TABLE.md"), "w").write("\n".join(out))
    print(len(rows), dict(c))

if __name__ == "__main__":
    main()
