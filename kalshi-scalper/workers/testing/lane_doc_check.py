#!/usr/bin/env python3
"""Lane doc check (Testing Desk, Nov 13, 2026; queue item 3 of the Head's 21:05Z message). Reads docs/ROTATION_LANE.md from a git ref (default origin/main) BY GIT, never a copy, prints its commit and sha256, checks that the phrases the
lane_block.py / spxoi1.py / oicore_shadow.py / liveshadow.py implementations depend on are in it, and re-runs their tests. `--write PATH` records the doc's hash and the results in a file.
Usage: lane_doc_check.py [--ref origin/main] [--write LANE_TEST_RECORD.md]
"""
import hashlib, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = "docs/ROTATION_LANE.md"
TESTS = ("test_lane_doc_check.py", "test_liveshadow.py", "test_lane_block.py", "test_spxoi1.py", "test_oicore_shadow.py", "test_place_report.py")
FILES = ("lane_doc_check.py", "liveshadow.py", "lane_block.py", "spxoi1.py", "oicore_shadow.py", "place_report.py") + TESTS
# the phrases each implementation decision rests on (normalised: whitespace collapsed, case kept)
PHRASES = [
    ("block size and days", "A block is 60 fillable signals in a row, within the last 21 days, on at least 7 different days"),
    ("bar", "Cash profit factor 1.3 or better on the block and 1.0 or better in each half"),
    ("rarer outcome", "At least 10 of the rarer outcome in the block"),
    ("favourites block", "the block is at least 150 signals and runs on until it holds at least 10 losses"),
    ("confirmation", "the next 30 fillable signals after a cleared block hold 1.0 or better"),
    ("slower log second look", "it must come at most 6 seconds after the signal"),
    ("R6 second look", "must come at most 4 seconds after it"),
    ("whole cents", "cents = floor(100 x cash in dollars + 1e-6)"),
    ("integer bar", "10 x W >= 13 x L"),
    ("half bar", "'1.0 or better' is W >= L"),
    ("L = 0", "A block, half or confirmation with L = 0 and W > 0 passes; W = 0 fails"),
    ("halves", "the first half is the first floor(n / 2) signals of the block and the second half is the rest"),
    ("day", "A day is a US Central calendar day"),
    ("order", "ordered by decision time on the clock of (f), then by market ticker ascending, then by side (yes before no)"),
    ("21 days", "21 x 24 hours"),
    ("88c class", "a signal whose limit is 88c or above is a favourite"),
    ("skips", "A signal that is a miss, is not fill-checked, or is skipped under (i) is not in any block"),
    ("void", "A void is in the count n and its fee is in L"),
    ("offset window", "120 most recent rows"),
    ("start time", "(l) Which signals count from the start time"),
    ("single-day test removed", "there is no single-day limit in the bar"),
]


def norm(t):
    return re.sub(r"\s+", " ", t.replace("**", "").replace("`", ""))


def check_text(text, phrases=PHRASES):
    n = norm(text)
    return [(name, ph, norm(ph) in n) for name, ph in phrases]


def git(*a):
    return subprocess.run(("git",) + a, cwd=HERE, capture_output=True, text=True, check=True).stdout


def read_doc(ref):
    return git("show", "%s:%s" % (ref, DOC)), git("rev-parse", ref).strip(), git("log", "-1", "--format=%h %ci %s", ref, "--", ":/" + DOC).strip()


def run_tests():
    res = {}
    for t in TESTS:
        p = subprocess.run([sys.executable, "-B", "-W", "ignore", os.path.join(HERE, t)], capture_output=True, text=True)
        res[t] = (p.returncode == 0, (p.stdout.strip().splitlines() or [""])[-1])
    return res


def sha(path):
    return hashlib.sha256(open(os.path.join(HERE, path), "rb").read()).hexdigest()


def build_record(ref="origin/main", tests=True):
    text, head, last = read_doc(ref)
    checks = check_text(text)
    out = ["# Lane test record (Testing Desk), generated by lane_doc_check.py", "",
           "Governing doc: `%s` at `%s` (ref head %s); last commit touching it: %s" % (DOC, ref, head, last), "",
           "sha256 of the doc: `%s` (%d bytes)" % (hashlib.sha256(text.encode()).hexdigest(), len(text.encode())), "", "## Phrases the implementations rest on", ""]
    out += ["- %s: %s" % (name, "FOUND" if ok else "MISSING: " + ph) for name, ph, ok in checks]
    if tests:
        out += ["", "## Tests re-run against it", ""] + ["- %s: %s (%s)" % (t, "PASS" if ok else "FAIL", line) for t, (ok, line) in run_tests().items()]
    out += ["", "## File hashes tested", ""] + ["- %s `%s`" % (f, sha(f)) for f in FILES if os.path.exists(os.path.join(HERE, f))]
    return "\n".join(out) + "\n", all(ok for _, _, ok in checks)


if __name__ == "__main__":
    a = sys.argv[1:]
    ref = a[a.index("--ref") + 1] if "--ref" in a else "origin/main"
    rec, ok = build_record(ref)
    if "--write" in a:
        open(a[a.index("--write") + 1], "w").write(rec)
    print(rec)
    sys.exit(0 if ok and "FAIL" not in rec else 1)
